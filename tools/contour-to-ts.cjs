// Turns a traced silhouette (contour3000.json from trace-silhouette.cjs) into a TypeScript module.
// Moves every point 4 source px toward the centre so no backdrop pixels stay on the cut edge.
// Usage: node tools/contour-to-ts.cjs <contour.json> <out.ts> <exportName> <sourceFile>
const fs = require("fs");
const [, , inFile, outFile, name, sourceFile] = process.argv;
const { center, points } = JSON.parse(fs.readFileSync(inFile, "utf8"));
const ERODE = 4;
const pts = points.map(([x, y]) => {
  const dx = x - center[0], dy = y - center[1], d = Math.hypot(dx, dy);
  return [Math.round((x - (dx / d) * ERODE) * 10) / 10, Math.round((y - (dy / d) * ERODE) * 10) / 10];
});
const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
const bbox = { x: Math.min(...xs), y: Math.min(...ys), w: Math.max(...xs) - Math.min(...xs), h: Math.max(...ys) - Math.min(...ys) };
const body = `// Generated by tools/contour-to-ts.cjs from ${sourceFile}. Do not edit by hand.
// Silhouette of the product in the source image's own pixels (traced, smoothed, eroded ${ERODE}px).
import type { Silhouette } from "../template/types";

export const ${name}: Silhouette = {
  bbox: ${JSON.stringify(bbox)},
  points: ${JSON.stringify(pts)},
};
`;
fs.writeFileSync(outFile, body);
console.log("wrote", outFile, pts.length, "points, bbox", bbox);
